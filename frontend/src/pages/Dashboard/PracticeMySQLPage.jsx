function PracticeMySQLPage() {
  const [searchParams, setSearchParams] = useSearchParams()
  const navigate = useNavigate()

  // Selected database from URL or localStorage
  const activeDbId =
    searchParams.get('db') || localStorage.getItem('active_sql_database') || 'employees_db'

  const currentDbInfo = DATABASE_INFO[activeDbId] || DATABASE_INFO.employees_db

  // Filters state
  const [difficultyFilter, setDifficultyFilter] = useState('ALL') // 'ALL' | 'Easy' | 'Medium' | 'Hard'
  const [searchQuery, setSearchQuery] = useState('')
  const [selectedTopic, setSelectedTopic] = useState('ALL')
  const [apiQuestions, setApiQuestions] = useState([])
  const [loading, setLoading] = useState(false)

  // Track solved questions in localStorage
  const [solvedMap, setSolvedMap] = useState(() => {
    try {
      const stored = localStorage.getItem('sqlforge_solved_questions')
      return stored ? JSON.parse(stored) : {}
    } catch {
      return {}
    }
  })

  // Modal / Quick Solve Drawer state
  const [activeSolveQuestion, setActiveSolveQuestion] = useState(null)
  const [solveCode, setSolveCode] = useState('')
  const [solveRunning, setSolveRunning] = useState(false)
  const [solveResult, setSolveResult] = useState(null)

  // Fetch from backend API if available, fallback gracefully
  useEffect(() => {
    let isMounted = true
    const fetchQuestions = async () => {
      setLoading(true)
      try {
        const res = await axios.get(
          `http://127.0.0.1:8000/api/v1/questions/?database=${activeDbId}`
        )
        if (isMounted && res.data && res.data.length > 0) {
          setApiQuestions(res.data)
        } else if (isMounted) {
          setApiQuestions(LOCAL_QUESTIONS[activeDbId] || LOCAL_QUESTIONS.employees_db)
        }
      } catch {
        if (isMounted) {
          // Graceful fallback to rich local questions dataset
          setApiQuestions(LOCAL_QUESTIONS[activeDbId] || LOCAL_QUESTIONS.employees_db)
        }
      } finally {
        if (isMounted) setLoading(false)
      }
    }

    fetchQuestions()
    return () => {
      isMounted = false
    }
  }, [activeDbId])

  // Merge API questions with local fallback hints & starter queries
  const allQuestionsForDb = useMemo(() => {
    const defaultList = LOCAL_QUESTIONS[activeDbId] || LOCAL_QUESTIONS.employees_db
    if (apiQuestions.length === 0) return defaultList

    return apiQuestions.map((apiQ, idx) => {
      const match = defaultList.find(
        (lq) => lq.title.toLowerCase() === apiQ.title.toLowerCase() || lq.id === apiQ.id
      )
      return {
        ...apiQ,
        tablesHint: match?.tablesHint || 'Relational Schema',
        starterQuery:
          match?.starterQuery ||
          `-- Write your query for: ${apiQ.title}\nSELECT * FROM ${
            activeDbId === 'employees_db' ? 'employees' : 'accounts'
          }\nLIMIT 10;`,
        index: idx + 1,
      }
    })
  }, [apiQuestions, activeDbId])

  // Extract unique topics for the selected database
  const availableTopics = useMemo(() => {
    const topics = Array.from(new Set(allQuestionsForDb.map((q) => q.topic).filter(Boolean)))
    return ['ALL', ...topics]
  }, [allQuestionsForDb])

  // Filter questions based on difficulty, topic, and search
  const filteredQuestions = useMemo(() => {
    return allQuestionsForDb.filter((q) => {
      const matchesDifficulty =
        difficultyFilter === 'ALL' || q.difficulty.toLowerCase() === difficultyFilter.toLowerCase()
      const matchesTopic = selectedTopic === 'ALL' || q.topic === selectedTopic
      const query = searchQuery.toLowerCase().trim()
      const matchesSearch =
        !query ||
        q.title.toLowerCase().includes(query) ||
        q.description.toLowerCase().includes(query) ||
        (q.topic && q.topic.toLowerCase().includes(query)) ||
        (q.tablesHint && q.tablesHint.toLowerCase().includes(query))

      return matchesDifficulty && matchesTopic && matchesSearch
    })
  }, [allQuestionsForDb, difficultyFilter, selectedTopic, searchQuery])

  // Count breakdown by difficulty
  const counts = useMemo(() => {
    const total = allQuestionsForDb.length
    const easy = allQuestionsForDb.filter((q) => q.difficulty.toLowerCase() === 'easy').length
    const medium = allQuestionsForDb.filter((q) => q.difficulty.toLowerCase() === 'medium').length
    const hard = allQuestionsForDb.filter((q) => q.difficulty.toLowerCase() === 'hard').length
    const solved = allQuestionsForDb.filter((q) => solvedMap[q.id]).length
    return { total, easy, medium, hard, solved }
  }, [allQuestionsForDb, solvedMap])

  // Switch database from page selector
  const handleSwitchDatabase = (dbId) => {
    setSearchParams({ db: dbId })
    localStorage.setItem('active_sql_database', dbId)
    setSelectedTopic('ALL')
    setDifficultyFilter('ALL')
    setSearchQuery('')
  }

  // Open the interactive solve drawer for a question
  const handleOpenSolve = (question) => {
    setActiveSolveQuestion(question)
    setSolveCode(question.starterQuery || '')
    setSolveResult(null)
  }

  // Simulate query run in the solve modal
  const handleRunSolveQuery = () => {
    setSolveRunning(true)
    setTimeout(() => {
      setSolveRunning(false)
      setSolveResult({
        status: 'SUCCESS',
        rows: 4,
        timeMs: 14.2,
        outputHeaders: ['id', 'name', 'status', 'metric_value'],
        outputRows: [
          [101, 'Elena Vance', 'ACTIVE', '$195,000.00'],
          [102, 'Marcus Chen', 'ACTIVE', '$182,000.00'],
          [103, 'Tariq Mansoor', 'ACTIVE', '$178,000.00'],
          [104, 'Aria Thorne', 'ACTIVE', '$165,000.00'],
        ],
      })
      toast.success('Query executed cleanly! 4 rows returned.')
    }, 600)
  }

  // Mark question solved
  const handleToggleSolved = (qId) => {
    setSolvedMap((prev) => {
      const next = { ...prev, [qId]: !prev[qId] }
      localStorage.setItem('sqlforge_solved_questions', JSON.stringify(next))
      if (next[qId]) {
        toast.success('Challenge marked as SOLVED!')
      }
      return next
    })
  }

  return (
    <div className="space-y-6">
      

      {/* 2. STATS & PROGRESS COUNTERS */}
      <div className="grid grid-cols-2 gap-4 sm:grid-cols-5">
        <div className="rounded-xl border border-forge-border bg-forge-card p-4 shadow-xs">
          <div className="text-xs font-medium uppercase tracking-wider text-forge-muted">
            Total Questions
          </div>
          <div className="mt-1.5 font-['Space_Grotesk'] text-2xl font-bold text-forge-text">
            {counts.total}
          </div>
        </div>

        <div className="rounded-xl border border-forge-border bg-forge-card p-4 shadow-xs">
          <div className="text-xs font-medium uppercase tracking-wider text-forge-success">
            Easy
          </div>
          <div className="mt-1.5 font-['Space_Grotesk'] text-2xl font-bold text-forge-success">
            {counts.easy}
          </div>
        </div>

        <div className="rounded-xl border border-forge-border bg-forge-card p-4 shadow-xs">
          <div className="text-xs font-medium uppercase tracking-wider text-yellow-500">
            Medium
          </div>
          <div className="mt-1.5 font-['Space_Grotesk'] text-2xl font-bold text-yellow-500">
            {counts.medium}
          </div>
        </div>

        <div className="rounded-xl border border-forge-border bg-forge-card p-4 shadow-xs">
          <div className="text-xs font-medium uppercase tracking-wider text-forge-accent">
            Hard
          </div>
          <div className="mt-1.5 font-['Space_Grotesk'] text-2xl font-bold text-forge-accent">
            {counts.hard}
          </div>
        </div>

        <div className="rounded-xl border border-forge-border bg-forge-card p-4 col-span-2 sm:col-span-1 shadow-xs">
          <div className="text-xs font-medium uppercase tracking-wider text-forge-muted">
            Solved by You
          </div>
          <div className="mt-1.5 font-['Space_Grotesk'] text-2xl font-bold text-forge-text">
            {counts.solved}{' '}
            <span className="text-xs font-normal text-forge-muted">/ {counts.total}</span>
          </div>
        </div>
      </div>

      {/* 3. FILTERS BAR: DIFFICULTY, TOPICS & SEARCH */}
      <div className="rounded-xl border border-forge-border bg-forge-card p-4 flex flex-col md:flex-row md:items-center justify-between gap-4 shadow-xs">
        {/* Difficulty Filter Tabs */}
        <div className="flex flex-wrap items-center gap-2">
          {[
            { id: 'ALL', label: `All (${counts.total})` },
            { id: 'Easy', label: `Easy (${counts.easy})` },
            { id: 'Medium', label: `Medium (${counts.medium})` },
            { id: 'Hard', label: `Hard (${counts.hard})` },
          ].map((tab) => {
            const isActive = difficultyFilter === tab.id
            return (
              <button
                key={tab.id}
                type="button"
                onClick={() => setDifficultyFilter(tab.id)}
                className={`rounded-lg px-3 py-1.5 text-xs font-medium transition-all cursor-pointer ${
                  isActive
                    ? 'bg-forge-accent text-[#101114] font-semibold shadow-xs'
                    : 'border border-forge-border bg-forge-surface text-forge-muted hover:text-forge-text'
                }`}
              >
                {tab.label}
              </button>
            )
          })}
        </div>

        {/* Search & Topic Selector */}
        <div className="flex flex-col sm:flex-row items-center gap-3">
          <select
            value={selectedTopic}
            onChange={(e) => setSelectedTopic(e.target.value)}
            className="w-full sm:w-auto rounded-lg border border-forge-border bg-forge-surface px-3 py-1.5 text-xs text-forge-text focus:border-forge-accent focus:outline-none"
          >
            {availableTopics.map((topic) => (
              <option key={topic} value={topic}>
                {topic === 'ALL' ? 'All Topics' : topic}
              </option>
            ))}
          </select>

          <div className="relative w-full sm:w-64">
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Search questions..."
              className="w-full rounded-lg border border-forge-border bg-forge-surface px-3 py-1.5 pl-8 text-xs text-forge-text placeholder-forge-muted/50 focus:border-forge-accent focus:outline-none"
            />
            <svg
              className="absolute left-2.5 top-2 h-3.5 w-3.5 text-forge-muted"
              fill="none"
              viewBox="0 0 24 24"
              stroke="currentColor"
            >
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M21 21l-6-6m2-5a7 7 0 11-14 0 7 7 0 0114 0z" />
            </svg>
          </div>
        </div>
      </div>

      {/* 4. QUESTIONS LISTING */}
      <div className="space-y-3">
        {loading ? (
          <div className="rounded-xl border border-forge-border bg-forge-card p-12 text-center text-xs text-forge-muted">
            <div className="inline-block h-6 w-6 animate-spin rounded-full border-2 border-forge-accent border-t-transparent mb-3" />
            <div>Loading questions for {currentDbInfo.name}...</div>
          </div>
        ) : filteredQuestions.length === 0 ? (
          <div className="rounded-xl border border-forge-border bg-forge-card p-12 text-center text-xs text-forge-muted space-y-3">
            <div>No questions matched the selected filters.</div>
            <button
              type="button"
              onClick={() => {
                setDifficultyFilter('ALL')
                setSelectedTopic('ALL')
                setSearchQuery('')
              }}
              className="rounded-lg border border-forge-accent bg-forge-accent px-4 py-2 text-xs font-semibold text-[#101114] hover:bg-forge-accent-hover cursor-pointer"
            >
              Reset Filters
            </button>
          </div>
        ) : (
          filteredQuestions.map((q, idx) => {
            const isSolved = Boolean(solvedMap[q.id])
            const difficultyBadgeClass =
              q.difficulty.toLowerCase() === 'easy'
                ? 'border-forge-success/40 text-forge-success bg-forge-success/10'
                : q.difficulty.toLowerCase() === 'medium'
                ? 'border-yellow-500/40 text-yellow-500 bg-yellow-500/10'
                : 'border-forge-accent/40 text-forge-accent bg-forge-accent/10'

            return (
              <div
                key={q.id || idx}
                className={`rounded-xl border bg-forge-card p-5 transition-all hover:border-forge-accent/60 flex flex-col md:flex-row md:items-center justify-between gap-4 shadow-xs ${
                  isSolved ? 'border-forge-border/80' : 'border-forge-border'
                }`}
              >
                {/* Left: Info */}
                <div className="space-y-2 flex-1">
                  <div className="flex flex-wrap items-center gap-2 text-xs">
                    <span className="font-mono text-forge-muted font-semibold">
                      Q{String(idx + 1).padStart(2, '0')}
                    </span>

                    <span
                      className={`rounded-full px-2.5 py-0.5 border text-[11px] font-semibold ${difficultyBadgeClass}`}
                    >
                      {q.difficulty}
                    </span>

                    {q.topic && (
                      <span className="rounded-full px-2.5 py-0.5 border border-forge-border bg-forge-surface text-forge-muted text-[11px]">
                        {q.topic}
                      </span>
                    )}

                    {isSolved && (
                      <span className="rounded-full px-2.5 py-0.5 border border-forge-success/40 bg-forge-success/15 text-forge-success text-[11px] font-semibold flex items-center gap-1">
                        <span>✓</span> Solved
                      </span>
                    )}
                  </div>

                  {/* Title */}
                  <h3 className="font-['Space_Grotesk'] text-base sm:text-lg font-bold text-forge-text hover:text-forge-accent transition-colors">
                    {q.title}
                  </h3>

                  {/* Description */}
                  <p className="text-xs text-forge-muted leading-relaxed line-clamp-2 max-w-3xl">
                    {q.description}
                  </p>

                  {/* Tables Hint */}
                  {q.tablesHint && (
                    <div className="text-xs text-forge-muted flex items-center gap-2">
                      <span className="font-semibold text-forge-text">Tables:</span>
                      <span className="font-mono text-forge-accent">{q.tablesHint}</span>
                    </div>
                  )}
                </div>

                {/* Right: Actions */}
                <div className="flex items-center gap-3 shrink-0 pt-2 md:pt-0 border-t md:border-t-0 border-forge-border/60">
                  <button
                    type="button"
                    onClick={() => handleToggleSolved(q.id)}
                    className={`rounded-lg h-9 px-3 border text-xs font-medium transition-colors cursor-pointer ${
                      isSolved
                        ? 'border-forge-success text-forge-success bg-forge-success/10 hover:bg-forge-success/15'
                        : 'border-forge-border text-forge-muted hover:border-forge-border hover:text-forge-text'
                    }`}
                  >
                    {isSolved ? '✓ Solved' : 'Mark Solved'}
                  </button>

                  <button
                    type="button"
                    onClick={() => handleOpenSolve(q)}
                    className="rounded-lg inline-flex items-center gap-1.5 border border-forge-accent bg-forge-accent px-4 py-2 text-xs font-semibold text-[#101114] transition-all hover:bg-forge-accent-hover hover:border-forge-accent-hover cursor-pointer"
                  >
                    <span>Solve</span>
                    <span>→</span>
                  </button>
                </div>
              </div>
            )
          })
        )}
      </div>

      {/* 5. INTERACTIVE SOLVE CHALLENGE MODAL */}
      {activeSolveQuestion && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 sm:p-6 bg-black/75 backdrop-blur-xs">
          <div className="relative w-full max-w-4xl rounded-2xl border border-forge-border bg-forge-card shadow-2xl max-h-[90vh] flex flex-col overflow-hidden">
            {/* Modal Header */}
            <div className="border-b border-forge-border bg-forge-card-alt/50 p-4 sm:p-5 flex items-center justify-between">
              <div>
                <div className="flex items-center gap-2 text-xs text-forge-muted">
                  <span className="font-semibold text-forge-accent">
                    Question #{activeSolveQuestion.id}
                  </span>
                  <span>•</span>
                  <span
                    className={`rounded-full px-2 py-0.5 text-[10px] font-semibold border ${
                      activeSolveQuestion.difficulty.toLowerCase() === 'easy'
                        ? 'border-forge-success text-forge-success'
                        : activeSolveQuestion.difficulty.toLowerCase() === 'medium'
                        ? 'border-yellow-500 text-yellow-500'
                        : 'border-forge-accent text-forge-accent'
                    }`}
                  >
                    {activeSolveQuestion.difficulty}
                  </span>
                  <span>•</span>
                  <span>{activeSolveQuestion.topic}</span>
                </div>
                <h2 className="font-['Space_Grotesk'] text-lg sm:text-xl font-bold text-forge-text mt-1">
                  {activeSolveQuestion.title}
                </h2>
              </div>

              <button
                type="button"
                onClick={() => setActiveSolveQuestion(null)}
                className="h-8 w-8 rounded-lg flex items-center justify-center border border-forge-border bg-forge-surface text-forge-muted hover:text-forge-text cursor-pointer"
                aria-label="Close"
              >
                ✕
              </button>
            </div>

            {/* Modal Body */}
            <div className="flex-1 overflow-y-auto p-4 sm:p-6 space-y-4">
              {/* Problem Statement Card */}
              <div className="rounded-xl border border-forge-border bg-forge-surface p-4">
                <div className="text-xs font-semibold text-forge-accent uppercase mb-1">
                  Problem Description
                </div>
                <p className="text-sm text-forge-text leading-relaxed">
                  {activeSolveQuestion.description}
                </p>

                {activeSolveQuestion.tablesHint && (
                  <div className="mt-3 pt-3 border-t border-forge-border flex items-center gap-2 text-xs text-forge-muted">
                    <span className="text-forge-text font-semibold">Target Schema:</span>
                    <span className="font-mono text-forge-accent">{activeSolveQuestion.tablesHint}</span>
                  </div>
                )}
              </div>

              {/* In-Browser Query Editor */}
              <div className="rounded-xl border border-forge-border bg-[#101114] overflow-hidden">
                <div className="flex items-center justify-between border-b border-[#303238] bg-[#141519] px-4 py-2 font-mono text-xs">
                  <span className="text-[#F4F1EA]">solution.sql</span>
                  <span className="text-[#52C788]">{currentDbInfo.engine}</span>
                </div>

                <div className="p-4">
                  <textarea
                    rows={6}
                    value={solveCode}
                    onChange={(e) => setSolveCode(e.target.value)}
                    placeholder="-- Write your SQL query here..."
                    className="w-full bg-transparent font-mono text-xs text-[#52C788] leading-6 resize-none focus:outline-none"
                    spellCheck="false"
                  />
                </div>

                <div className="flex items-center justify-between border-t border-[#303238] bg-[#141519] p-3">
                  <div className="text-xs text-[#92949B]">
                    Press [Ctrl + Enter] to execute
                  </div>

                  <button
                    type="button"
                    onClick={handleRunSolveQuery}
                    disabled={solveRunning}
                    className="rounded-lg border border-[#FF6B35] bg-[#FF6B35] px-4 py-1.5 text-xs font-semibold text-[#101114] hover:bg-[#FF8354] cursor-pointer"
                  >
                    {solveRunning ? 'Running...' : '▶ Run Query'}
                  </button>
                </div>
              </div>

              {/* Execution Result Box */}
              {solveResult && (
                <div className="rounded-xl border border-forge-border bg-forge-surface p-4 space-y-3">
                  <div className="flex items-center justify-between text-xs">
                    <span className="text-forge-success font-semibold flex items-center gap-1.5">
                      <span className="h-2 w-2 rounded-full bg-forge-success animate-pulse" />✓ Query
                      Executed Successfully ({solveResult.timeMs}ms)
                    </span>
                    <span className="text-forge-muted font-mono">{solveResult.rows} rows returned</span>
                  </div>

                  <div className="overflow-x-auto rounded-lg border border-forge-border bg-[#101114]">
                    <table className="w-full text-left font-mono text-xs text-[#F4F1EA]">
                      <thead>
                        <tr className="border-b border-[#303238] bg-[#191B20] text-[11px] text-[#92949B]">
                          {solveResult.outputHeaders.map((h) => (
                            <th key={h} className="p-2.5">
                              {h}
                            </th>
                          ))}
                        </tr>
                      </thead>
                      <tbody className="divide-y divide-[#303238]/60">
                        {solveResult.outputRows.map((row, rIdx) => (
                          <tr key={rIdx}>
                            {row.map((cell, cIdx) => (
                              <td key={cIdx} className="p-2.5">
                                {cell}
                              </td>
                            ))}
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                </div>
              )}
            </div>

            {/* Modal Footer */}
            <div className="border-t border-forge-border bg-forge-card-alt/50 p-4 flex flex-col sm:flex-row items-center justify-between gap-3">
              <button
                type="button"
                onClick={() => handleToggleSolved(activeSolveQuestion.id)}
                className={`rounded-lg text-xs font-medium px-3.5 py-1.5 border transition-colors cursor-pointer ${
                  solvedMap[activeSolveQuestion.id]
                    ? 'border-forge-success text-forge-success bg-forge-success/10'
                    : 'border-forge-border text-forge-muted hover:text-forge-text'
                }`}
              >
                {solvedMap[activeSolveQuestion.id] ? '✓ Solved (Click to unmark)' : 'Mark as Solved'}
              </button>

              <div className="flex items-center gap-2">
                <button
                  type="button"
                  onClick={() => setActiveSolveQuestion(null)}
                  className="rounded-lg border border-forge-border px-4 py-1.5 text-xs font-medium text-forge-muted hover:text-forge-text cursor-pointer"
                >
                  Close
                </button>
                <button
                  type="button"
                  onClick={() => {
                    navigate(
                      `/dashboard/editor?questionId=${activeSolveQuestion.id}&db=${activeDbId}`
                    )
                  }}
                  className="rounded-lg border border-forge-accent bg-forge-accent px-4 py-1.5 text-xs font-semibold text-[#101114] hover:bg-forge-accent-hover cursor-pointer"
                >
                  Open in Full Editor →
                </button>
              </div>
            </div>
          </div>
        </div>
      )}
    </div>
  )
}

export default PracticeMySQLPage

